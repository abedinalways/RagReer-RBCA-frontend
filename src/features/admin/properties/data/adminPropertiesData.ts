export function getAdminPropertyDetails(id: string): AdminPropertyDetailData {
  const property = mockAdminProperties.find((p) => p.id === id || p.propertyCode === id);
  if (!property) return defaultAdminPropertyDetail;

  return {
    ...defaultAdminPropertyDetail,
    id: property.id,
    propertyCode: property.propertyCode,
    title: property.title || defaultAdminPropertyDetail.title,
    status: property.status,
    category: property.propertyType,
    location: {
      ...defaultAdminPropertyDetail.location,
      address: property.propertyAddress,
    },
  };
}
